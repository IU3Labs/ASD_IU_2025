import java.util.Scanner;

public class RotatedSortedArrayMin {

    /**
     * Находит минимальный элемент в циклически сдвинутом отсортированном массиве
     * Использует модифицированный бинарный поиск
     *
     * @param nums - циклически сдвинутый отсортированный массив
     * @return минимальный элемент массива
     */
    public static int findMin(int[] nums) {
        int left = 0;
        int right = nums.length - 1;

        // Если массив не был сдвинут или содержит один элемент
        if (nums[left] <= nums[right]) {
            return nums[left];
        }

        // Бинарный поиск точки поворота (места, где происходит сдвиг)
        while (left <= right) {
            int mid = left + (right - left) / 2;

            // Проверяем, является ли mid точкой поворота
            // Точка поворота - это элемент, который больше следующего элемента
            if (mid < nums.length - 1 && nums[mid] > nums[mid + 1]) {
                return nums[mid + 1];
            }

            // Проверяем, является ли mid-1 точкой поворота
            if (mid > 0 && nums[mid - 1] > nums[mid]) {
                return nums[mid];
            }

            // Решаем, в какую половину продолжить поиск
            if (nums[mid] > nums[0]) {
                // Левая половина отсортирована, точка поворота справа
                left = mid + 1;
            } else {
                // Правая половина отсортирована, точка поворота слева
                right = mid - 1;
            }
        }

        return nums[0]; // На случай, если массив не был сдвинут
    }

    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);

        System.out.println("Поиск минимального элемента в циклически сдвинутом отсортированном массиве");
        System.out.println("=========================================================================");

        // Ввод размера массива
        System.out.print("Введите количество элементов в массиве: ");
        int n = scanner.nextInt();

        // Ввод элементов массива
        int[] nums = new int[n];
        System.out.println("Введите элементы массива (отсортированный массив, циклически сдвинутый):");
        for (int i = 0; i < n; i++) {
            System.out.print("Элемент " + (i + 1) + ": ");
            nums[i] = scanner.nextInt();
        }

        // Вывод введенного массива
        System.out.println("\nВведенный массив:");
        for (int num : nums) {
            System.out.print(num + " ");
        }
        System.out.println();

        // Поиск минимального элемента
        int minElement = findMin(nums);

        // Вывод результата
        System.out.println("\nРезультат:");
        System.out.println("Минимальный элемент: " + minElement);

        scanner.close();
    }
}

/**Основа доказательства:

На каждой итерации область поиска уменьшается вдвое

Начальный размер: N элементов

После k итераций размер области поиска: N/2^k

        Поиск заканчивается, когда N/2^k ≤ 1

Решая: 2^k ≥ N ⇒ k ≥ log₂N

Формальное доказательство:

Базовый случай: Для массива размером 1 требуется 0 сравнений

Рекуррентное соотношение: T(N) = T(N/2) + O(1)

Решение: T(N) = O(log N)

Каждая операция внутри цикла выполняется за O(1), а количество итераций O(log N), поэтому общая сложность O(log N).
 */